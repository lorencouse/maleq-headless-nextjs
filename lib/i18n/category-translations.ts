/** Decode the handful of HTML entities WordPress leaves in stored term names. */
function decodeEntities(s: string): string {
  return s
    .replace(/&amp;/gi, '&')
    .replace(/&#0*38;/g, '&')
    .replace(/&quot;/gi, '"')
    .replace(/&#0*39;/g, "'")
    .replace(/&apos;/gi, "'")
    .replace(/&#8217;/g, '’')
    .replace(/&#8211;/g, '–')
    .replace(/&#8212;/g, '—')
    .replace(/&nbsp;/gi, ' ');
}

/**
 * Localize a category name by slug.
 *
 * Returns the mapped label for the locale, or the entity-decoded English name
 * when there's no mapping (unmapped slug, brand category, or `en`/untranslated
 * locale). Safe to call on the server or client.
 */
export function localizeCategoryName(
  slug: string | undefined,
  fallbackName: string,
  locale: string,
): string {
  const hit = slug ? CATEGORY_NAMES[locale]?.[slug] : undefined;
  return hit ?? decodeEntities(fallbackName ?? '');
}

/**
 * Client hook: returns a `(slug, name) => localizedName` function bound to the
 * active UI locale. Use in client components that render category names.
 */
export function useLocalizedCategoryName(): (slug: string | undefined, name: string) => string {
  const locale = useLocale();
  return (slug, name) => localizeCategoryName(slug, name, locale);
}
